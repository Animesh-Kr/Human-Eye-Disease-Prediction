def run_epoch(model, loader, train=True):
    model.train() if train else model.eval()
    total_loss = 0
    all_preds, all_labels, all_probs = [], [], []
    with torch.set_grad_enabled(train):
        for imgs, labels in loader:
            imgs, labels = imgs.to(DEVICE), labels.to(DEVICE)
            with torch.autocast(device_type="cuda", dtype=torch.float16):
                logits = model(imgs)
                loss   = criterion(logits, labels)
            if train:
                optimizer.zero_grad()
                scaler.scale(loss).backward()
                scaler.unscale_(optimizer)
                torch.nn.utils.clip_grad_norm_(
                    [p for p in model.parameters() if p.requires_grad], 0.5)
                scaler.step(optimizer)
                scaler.update()
                scheduler.step()

            # ── NaN guard ─────────────────────────────────────
            logits_f = logits.float()
            if torch.isnan(logits_f).any() or torch.isinf(logits_f).any():
                print("  ⚠️  NaN/Inf in logits — skipping batch")
                continue

            probs = torch.softmax(logits_f, 1).detach().cpu().numpy()
            preds = logits_f.argmax(1).detach().cpu().numpy()
            total_loss += loss.item() * len(labels)
            all_preds.extend(preds)
            all_labels.extend(labels.cpu().numpy())
            all_probs.extend(probs)

    n = len(all_labels)
    return (total_loss/n,
            accuracy_score(all_labels, all_preds),
            roc_auc_score(all_labels, all_probs, multi_class="ovr", average="macro"),
            f1_score(all_labels, all_preds, average="macro"),
            f1_score(all_labels, all_preds, average=None),
            all_probs)

def train_model(model, epochs, ckpt_name, resume_path):
    ckpt_path   = os.path.join(OUTPUT_DIR, ckpt_name)
    drusen_idx  = CLASSES.index("DRUSEN")
    start_epoch = 1
    best_auc    = 0.0
    history     = []

    # Extract seed from ckpt_name for history JSON path
    # ckpt_name format: best_{MODE}_seed{s}.pth
    seed_str = ckpt_name.replace(f"best_{MODE}_seed", "").replace(".pth", "")

    # ── Single resume check block (no duplicates) ─────────────
    if os.path.exists(resume_path):
        print(f"Resume file found — loading state...")
        state = torch.load(resume_path, map_location=DEVICE, weights_only=False)

        # Already completed — skip to evaluation
        if state["epoch"] >= epochs:
            print(f"Checkpoint complete ({state['epoch']}/{epochs} epochs) "
                  f"— skipping to evaluation.")
            model.load_state_dict(state["model_state"])
            return ckpt_path, state["history"]

        # Partial — resume from last saved epoch
        model.load_state_dict(state["model_state"])
        optimizer.load_state_dict(state["optimizer_state"])
        scheduler.load_state_dict(state["scheduler_state"])
        scaler.load_state_dict(state["scaler_state"])
        start_epoch = state["epoch"] + 1
        best_auc    = state["best_auc"]
        history     = state["history"]
        print(f"Resuming from epoch {start_epoch}/{epochs}  "
              f"best_auc so far: {best_auc:.4f}")
    else:
        # No resume .pt — check for history JSON as fallback
        history_json = os.path.join(OUTPUT_DIR,
                                    f"history_{MODE}_seed{seed_str}.json")
        if os.path.exists(history_json):
            with open(history_json, "r") as hf:
                history = json.load(hf)
            print(f"No resume .pt but history JSON found "
                  f"({len(history)} epochs recovered).")
        else:
            print("No resume file — starting fresh.")

    print(f"\n{'='*62}")
    print(f"  {MODE} | epochs {start_epoch}→{epochs} | {DEVICE}")
    print(f"  Saves to Drive every epoch — safe to disconnect")
    print(f"{'='*62}")

    for epoch in range(start_epoch, epochs + 1):
        t0  = time.time()
        tr  = run_epoch(model, train_loader, train=True)
        vl  = run_epoch(model, val_loader,   train=False)
        drusen_vl = float(vl[4][drusen_idx])

        print(f"Ep{epoch:3d}/{epochs} "
              f"tr_acc={tr[1]:.4f} tr_auc={tr[2]:.4f} | "
              f"vl_acc={vl[1]:.4f} vl_auc={vl[2]:.4f} "
              f"drusen_f1={drusen_vl:.4f} [{time.time()-t0:.0f}s]")

        history.append({"epoch": epoch,
                        "tr_acc": round(tr[1],4), "tr_auc": round(tr[2],4),
                        "vl_acc": round(vl[1],4), "vl_auc": round(vl[2],4),
                        "vl_f1":  round(vl[3],4),
                        "vl_drusen_f1": round(drusen_vl,4)})

        # ── Save history as plain JSON every epoch ─────────────
        with open(os.path.join(OUTPUT_DIR,
                  f"history_{MODE}_seed{seed_str}.json"), "w") as hf:
            json.dump(history, hf)

        if vl[2] > best_auc:
            best_auc = vl[2]
            torch.save(model.state_dict(), ckpt_path)
            print(f"          ✅ Best saved → Drive  val_auc={vl[2]:.4f}")

        # ── Save full resume state every epoch ─────────────────
        torch.save({"epoch": epoch, "best_auc": best_auc, "history": history,
                    "model_state":     model.state_dict(),
                    "optimizer_state": optimizer.state_dict(),
                    "scheduler_state": scheduler.state_dict(),
                    "scaler_state":    scaler.state_dict()}, resume_path)

    print(f"Training complete. Best val_auc: {best_auc:.4f}")
    return ckpt_path, history

