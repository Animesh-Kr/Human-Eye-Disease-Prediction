def custom_forward(self, x):
    x = self.forward_features(x)
    return self.head(x)

def build_retfound(weights_path, n_classes=4):
    model = models_vit.__dict__['vit_large_patch16'](
        num_classes=n_classes, drop_path_rate=0.2, global_pool=True)
    ckpt  = torch.load(weights_path, map_location='cpu', weights_only=False)
    ckpt_model = ckpt['model']
    sd   = model.state_dict()
    for k in ['head.weight', 'head.bias']:
        if k in ckpt_model and ckpt_model[k].shape != sd[k].shape:
            del ckpt_model[k]
    interpolate_pos_embed(model, ckpt_model)
    model.load_state_dict(ckpt_model, strict=False)
    model.fc_norm = nn.LayerNorm(1024)
    model.head    = nn.Linear(1024, n_classes)
    trunc_normal_(model.head.weight, std=2e-5)
    model.forward = types.MethodType(custom_forward, model)
    return model

