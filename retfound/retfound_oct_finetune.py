# ── Step 4: Fast run_epoch with bfloat16 + grad accum ─────────
def run_epoch_fast(model, loader, optimizer, scheduler,
                   scaler, criterion, train=True):
    model.train() if train else model.eval()
    total_loss = 0
    all_preds, all_labels, all_probs = [], [], []

    with torch.set_grad_enabled(train):
        for batch_idx, (imgs, labels) in enumerate(loader):
            imgs, labels = imgs.to(DEVICE), labels.to(DEVICE)

            with torch.autocast(device_type="cuda", dtype=AMP_DTYPE):
                logits = model(imgs)
                loss   = criterion(logits, labels)
                if train:
                    loss = loss / ACCUM_STEPS  # scale for accumulation

            if train:
                scaler.scale(loss).backward()
                if (batch_idx + 1) % ACCUM_STEPS == 0:
                    scaler.unscale_(optimizer)
                    torch.nn.utils.clip_grad_norm_(
                        [p for p in model.parameters()
                         if p.requires_grad], 0.5)
                    scaler.step(optimizer)
                    scaler.update()
                    optimizer.zero_grad()
                    scheduler.step()

            # NaN guard
            logits_f = logits.float()
            if torch.isnan(logits_f).any() or torch.isinf(logits_f).any():
                continue

            probs = torch.softmax(logits_f, 1).detach().cpu().numpy()
            preds = logits_f.argmax(1).detach().cpu().numpy()
            total_loss += loss.item() * ACCUM_STEPS * len(labels)
            all_preds.extend(preds)
            all_labels.extend(labels.cpu().numpy())
            all_probs.extend(probs)

    n = len(all_labels)
    if n == 0:
        return (0, 0, 0, 0, np.zeros(4), [])
    return (
        total_loss / n,
        accuracy_score(all_labels, all_preds),
        roc_auc_score(all_labels, all_probs,
                      multi_class="ovr", average="macro"),
        f1_score(all_labels, all_preds, average="macro"),
        f1_score(all_labels, all_preds, average=None),
        all_probs,
    )

# ── Step 5: Fast train_model using new loaders ────────────────
def train_model_fast(model, epochs, ckpt_name, resume_path,
                     optimizer, scheduler, criterion, scaler):
    ckpt_path   = os.path.join(OUTPUT_DIR, ckpt_name)
    drusen_idx  = CLASSES.index("DRUSEN")
    seed_str    = ckpt_name.replace(f"best_{MODE}_seed","").replace(".pth","")
    start_epoch = 1
    best_auc    = 0.0
    history     = []

    if os.path.exists(resume_path):
        state = torch.load(resume_path, map_location=DEVICE,
                           weights_only=False)
        if state["epoch"] >= epochs:
            print(f"Complete ({state['epoch']}/{epochs}) — skipping.")
            model.load_state_dict(state["model_state"])
            return ckpt_path, state["history"]
        model.load_state_dict(state["model_state"])
        optimizer.load_state_dict(state["optimizer_state"])
        scheduler.load_state_dict(state["scheduler_state"])
        scaler.load_state_dict(state["scaler_state"])
        start_epoch = state["epoch"] + 1
        best_auc    = state["best_auc"]
        history     = state["history"]
        print(f"Resuming epoch {start_epoch}/{epochs}  "
              f"best_auc={best_auc:.4f}")
    else:
        hist_json = os.path.join(OUTPUT_DIR,
                                 f"history_{MODE}_seed{seed_str}.json")
        if os.path.exists(hist_json):
            with open(hist_json) as hf:
                history = json.load(hf)
            print(f"History JSON found ({len(history)} epochs).")
            # FIX: Fast-forward start epoch and load weights if complete
            start_epoch = len(history) + 1
            if start_epoch > epochs:
                print(f"Complete ({len(history)}/{epochs}) — skipping.")
                if os.path.exists(ckpt_path):
                    model.load_state_dict(torch.load(ckpt_path, map_location=DEVICE, weights_only=False))
                return ckpt_path, history
        else:
            print("Starting fresh.")

    print(f"\n{'='*62}")
    print(f"  {MODE} seed={seed_str} | ep {start_epoch}→{epochs} | "
          f"batch={BATCH_SIZE_FF} accum={ACCUM_STEPS} | {AMP_DTYPE}")
    print(f"{'='*62}")

    for epoch in range(start_epoch, epochs + 1):
        t0        = time.time()
        tr        = run_epoch_fast(model, train_loader_ff, optimizer,
                                   scheduler, scaler, criterion, True)
        vl        = run_epoch_fast(model, val_loader_ff,  optimizer,
                                   scheduler, scaler, criterion, False)
        drusen_vl = float(vl[4][drusen_idx])
        elapsed   = time.time() - t0

        print(f"Ep{epoch:3d}/{epochs} "
              f"tr_acc={tr[1]:.4f} tr_auc={tr[2]:.4f} | "
              f"vl_acc={vl[1]:.4f} vl_auc={vl[2]:.4f} "
              f"drusen_f1={drusen_vl:.4f} [{elapsed:.0f}s]")

        history.append({"epoch": epoch,
                        "tr_acc": round(tr[1],4), "tr_auc": round(tr[2],4),
                        "vl_acc": round(vl[1],4), "vl_auc": round(vl[2],4),
                        "vl_f1":  round(vl[3],4),
                        "vl_drusen_f1": round(drusen_vl,4)})

        with open(os.path.join(OUTPUT_DIR,
                  f"history_{MODE}_seed{seed_str}.json"), "w") as hf:
            json.dump(history, hf)

        if vl[2] > best_auc:
            best_auc = vl[2]
            torch.save(model.state_dict(), ckpt_path)
            print(f"          ✅ Best saved  val_auc={vl[2]:.4f}")

        torch.save({"epoch": epoch, "best_auc": best_auc,
                    "history": history,
                    "model_state":     model.state_dict(),
                    "optimizer_state": optimizer.state_dict(),
                    "scheduler_state": scheduler.state_dict(),
                    "scaler_state":    scaler.state_dict()},
                   resume_path)

    print(f"Done. Best val_auc: {best_auc:.4f}")
    return ckpt_path, history

