import torch.optim as optim

def setup_training(model_obj, mode, lr, n_layers, lr_decay):
    if mode == "linear_probe":
        for name, param in model_obj.named_parameters():
            if "head" not in name and "fc_norm" not in name:
                param.requires_grad = False
        trainable = sum(p.numel() for p in model_obj.parameters()
                        if p.requires_grad)
        print(f"Linear probe: {trainable:,} trainable params")
        optimizer = optim.AdamW(
            [p for p in model_obj.parameters() if p.requires_grad],
            lr=lr, weight_decay=0.05)
    else:                                               # full_finetune
        param_groups = []
        for i in range(n_layers):
            lps = [p for n, p in model_obj.named_parameters()
                   if f"blocks.{i}." in n]
            if lps:
                param_groups.append({
                    "params": lps,
                    "lr": lr * (lr_decay ** (n_layers - i))
                })
        head_ps = [p for n, p in model_obj.named_parameters()
                   if "head" in n or "fc_norm" in n]
        param_groups.append({"params": head_ps, "lr": lr})
        optimizer = optim.AdamW(param_groups, weight_decay=0.05)
        print(f"Full finetune: "
              f"{sum(p.numel() for p in model_obj.parameters())/1e6:.1f}M params")

    scheduler = optim.lr_scheduler.OneCycleLR(
        optimizer, max_lr=lr, epochs=EPOCHS,
        steps_per_epoch=len(train_loader),
        pct_start=WARMUP_PCT, anneal_strategy='cos')
    return optimizer, scheduler

